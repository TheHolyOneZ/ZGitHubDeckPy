from __future__ import annotations

from .report import Cell, Report, Section

MARK = "✻"


def escape(text: str) -> str:
    return (
        str(text)
        .replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("\r", " ")
        .replace("\n", " ")
        .strip()
    )


def _cell(cell: Cell) -> str:
    if cell.chips:
        return " ".join(f"`{escape(name)}`" for name, _ in cell.chips) or "—"

    text = escape(cell.text) or "—"
    if cell.kind == "mono" and not cell.href:
        return f"`{text}`"
    if cell.href:
        return f"[{text}]({cell.href})"
    return text


def _table(section: Section) -> list[str]:
    header = "| " + " | ".join(escape(c.label) for c in section.columns) + " |"
    divider = "| " + " | ".join(
        "---:" if c.align == "right" else "---" for c in section.columns
    ) + " |"

    lines = [header, divider]
    for row in section.rows:
        lines.append("| " + " | ".join(_cell(cell) for cell in row) + " |")
    return lines


def render(report: Report) -> str:
    out: list[str] = [f"# {report.title}", ""]

    if report.subtitle:
        out += [f"**{report.subtitle}**", ""]

    stamp = report.generated_at.astimezone().strftime("%d %B %Y at %H:%M")
    byline = f"> Generated by **ZDECK** {MARK} on {stamp}"
    if report.owner:
        byline += f" for [@{report.owner}](https://github.com/{report.owner})"
    out.append(byline)
    if report.filter_text:
        out.append(">")
        out.append(f"> Filtered by `{escape(report.filter_text)}`")
    out.append("")

    if report.stats:
        out += ["## Summary", ""]
        out += ["| | |", "|---|---|"]
        for label, value in report.stats:
            out.append(f"| {escape(label)} | **{escape(value)}** |")
        out.append("")

    for section in report.sections:
        out.append(f"## {section.title}")
        out.append("")
        if section.subtitle:
            out += [section.subtitle, ""]
        if section.empty:
            out += ["_Nothing to show._", ""]
            continue
        out += _table(section)
        out.append("")
        if section.note:
            out += [f"> {section.note}", ""]

    out += [
        "---",
        "",
        f"<sub>{report.row_count:,} rows · "
        "made with [ZDECK](https://github.com/TheHolyOneZ) — "
        "a GitHub dashboard for the terminal.</sub>",
        "",
    ]
    return "\n".join(out)
